"""Plot Chapter 4.3 warning curves from a saved trial JSON."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from experiments.exp_43_main import plot_fig43


def main() -> None:
    parser = argparse.ArgumentParser(description="Plot Chapter 4.3 warning curves.")
    parser.add_argument("--trial", required=True, help="Path to trial_XX.json generated by experiments.exp_43_main.")
    parser.add_argument("--output", default="data/results/ch4_3/fig43.png")
    args = parser.parse_args()

    with Path(args.trial).open("r", encoding="utf-8") as handle:
        result = json.load(handle)
    plot_fig43(result, args.output)
    print(f"[exp_43_plot] saved {Path(args.output)}")


if __name__ == "__main__":
    main()
